#!/usr/bin/env python3
"""Embed the complete application as deterministic gzip assets in ESP32 flash."""
import argparse
import gzip
import hashlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT/'03_agente_frontend'
OUTPUT = ROOT/'02_agente_firmware'/'SmartConnect_Firmware'/'web_ui.h'
ASSETS = [('index.html','text/html'),('app.css','text/css'),('app.js','application/javascript'),('manifest.json','application/manifest+json'),('service-worker.js','application/javascript'),('icon.svg','image/svg+xml'),('icon-192.png','image/png'),('icon-512.png','image/png')]

def generate():
    lines = ['#pragma once', '#include <pgmspace.h>', '#include "safe_web_server.h"', '// Generated by embed_ui.py. Do not edit.']
    raw_total = compressed_total = 0
    routes = []
    for index,(name,mime) in enumerate(ASSETS):
        raw=(FRONTEND/name).read_bytes()
        compressed=gzip.compress(raw,compresslevel=9,mtime=0)
        symbol=f'WEB_ASSET_{index}'
        raw_total+=len(raw); compressed_total+=len(compressed)
        lines += [f'// {name}: {len(raw)} bytes; SHA256 {hashlib.sha256(raw).hexdigest()}',f'static const uint8_t {symbol}[] PROGMEM={{']
        lines += [','.join(f'0x{b:02x}' for b in compressed[i:i+24])+',' for i in range(0,len(compressed),24)]
        lines += ['};']
        for route in (['/','/index.html'] if index==0 else ['/'+name]):
            routes += [f'  server.on("{route}",HTTP_GET,[&server](){{',
                '    server.sendHeader("Content-Encoding","gzip");',
                '    server.sendHeader("Cache-Control","no-cache");',
                '    server.sendHeader("X-Content-Type-Options","nosniff");',
                '    server.sendHeader("Content-Security-Policy","default-src \'self\'; script-src \'self\'; style-src \'self\' \'unsafe-inline\'; img-src \'self\' data:; connect-src \'self\'; object-src \'none\'; frame-ancestors \'none\'; base-uri \'self\'");',
                f'    server.send_P(200,"{mime}",reinterpret_cast<const char*>({symbol}),sizeof({symbol}));',
                '  });']
    lines += ['inline void registerWebAssets(SafeWebServer& server) {']+routes+['}','']
    return '\n'.join(lines), raw_total, compressed_total

def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    content,raw,packed=generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8')!=content:
            raise SystemExit('Bundle desatualizado. Execute python 04_agente_devops/embed_ui.py')
    else: OUTPUT.write_text(content,encoding='utf-8',newline='\n')
    print(f'Assets: {raw} bytes -> {packed} bytes gzip ({100*(1-packed/raw):.1f}% menor). Bundle sincronizado.')
if __name__=='__main__': main()
